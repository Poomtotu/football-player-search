today = date(2026, 8, 31)
root = Path(__file__).resolve().parents[1]
files = [root / 'backend/data/players.json', root / 'backend/data/mock_players.json']
for path in files:
    if not path.exists():
        continue
    players = json.loads(path.read_text(encoding='utf-8'))
    if len(players) != 100:
        raise RuntimeError(f'{path}: expected 100 players, got {len(players)}')
    for i, player in enumerate(players):
        b = date.fromisoformat(dates[i])
        player['birth_date'] = dates[i]
        player['age'] = today.year - b.year - ((today.month, today.day) < (b.month, b.day))
    path.write_text(json.dumps(players, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'updated {path.name}: {len(players)} players')

